  /* 把行描述转成 SVG path */
  function pixPath(rows) {
    const rects = [];
    let y = 0;
    for (const row of String(rows).split('/')) {
      for (const seg of row.split(',')) {
        const m = seg.trim().match(/^(\d+)-(\d+)$/);
        if (m) rects.push({ x1: +m[1], x2: +m[2], y });
      }
      y++;
    }
    if (!rects.length) return '';
    // 求 bbox，整体居中到 16×16
    const minX = Math.min(...rects.map((r) => r.x1));
    const maxX = Math.max(...rects.map((r) => r.x2));
    const minY = Math.min(...rects.map((r) => r.y));
    const maxY = Math.max(...rects.map((r) => r.y));
    const w = maxX - minX + 1;
    const h = maxY - minY + 1;
    const dx = Math.round((16 - w) / 2) - minX;
    const dy = Math.round((16 - h) / 2) - minY;
    return rects
      .map((r) => `M${r.x1 + dx} ${r.y + dy}h${r.x2 - r.x1 + 1}v1H${r.x1 + dx}z`)
      .join('');
  }

